"use client";

import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuRadioGroup,
  DropdownMenuRadioItem,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { DEFAULT_GENERAL, useStore, type GeneralSettings as General } from "@/lib/store";
import { cn } from "@/lib/utils";
import { ChevronDownIcon } from "lucide-react";
import type { ReactNode } from "react";
import { PageScroll } from "./page-scroll";

const TITLES: { id: General["chatTitles"]; label: string }[] = [
  { id: "message", label: "From First Message" },
  { id: "model", label: "Generated by Model" },
];

function Switch({ checked, onChange, label }: { checked: boolean; onChange: (checked: boolean) => void; label: string }) {
  return (
    <button
      aria-checked={checked}
      aria-label={label}
      className={cn("relative inline-flex h-4 w-7 shrink-0 items-center rounded-full p-0.5", checked ? "bg-foreground/80" : "bg-foreground/15")}
      onClick={() => onChange(!checked)}
      role="switch"
      type="button"
    >
      <span className={cn("size-3 rounded-full bg-white shadow-sm", checked ? "translate-x-3" : "translate-x-0")} />
    </button>
  );
}

function Row({ label, hint, children }: { label: string; hint: string; children: ReactNode }) {
  return (
    <div className="flex items-center gap-6 px-3 py-3">
      <div className="min-w-0 flex-1 space-y-1">
        <div className="text-[13px] leading-[1.4]">{label}</div>
        <div className="text-[12px] leading-[1.35] text-muted-foreground">{hint}</div>
      </div>
      <div className="flex shrink-0 flex-col items-end gap-1">{children}</div>
    </div>
  );
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <div className="mt-7 first:mt-0">
      <h2 className="mb-2 px-2 text-[12px] leading-[1.35] text-muted-foreground">{title}</h2>
      <section className="divide-y overflow-hidden rounded-[12px] border bg-card">{children}</section>
    </div>
  );
}

/** Settings → General: notifications and how chats are named. */
export function GeneralSettings() {
  const { general: stored, setGeneral } = useStore();
  const general = { ...DEFAULT_GENERAL, ...stored };
  const titles = TITLES.find((item) => item.id === general.chatTitles) ?? TITLES[0];
  const anyNotice = general.notifyFinished || general.notifyWaiting || general.notifyFailed;

  return (
    <PageScroll>
      <div className="mx-auto flex w-full max-w-xl flex-col">
        <h1 className="mb-6 pl-2 font-medium text-[15px] leading-[1.6]">General</h1>

        <Section title="Notifications">
          <Row hint="Notify when a response finishes while Endurance is in the background" label="Response Complete">
            <Switch checked={general.notifyFinished} label="Response Complete" onChange={(notifyFinished) => setGeneral({ notifyFinished })} />
          </Row>
          <Row hint="Notify when a response needs your approval or input" label="Action Required">
            <Switch checked={general.notifyWaiting} label="Action Required" onChange={(notifyWaiting) => setGeneral({ notifyWaiting })} />
          </Row>
          <Row hint="Notify when a response ends with an error" label="Response Failed">
            <Switch checked={general.notifyFailed} label="Response Failed" onChange={(notifyFailed) => setGeneral({ notifyFailed })} />
          </Row>
          <Row hint="Play the system alert sound with notifications" label="Notification Sound">
            <Switch checked={general.notifySound && anyNotice} label="Notification Sound" onChange={(notifySound) => setGeneral({ notifySound })} />
          </Row>
        </Section>

        <Section title="Chats">
          <Row
            hint={
              general.chatTitles === "model"
                ? "The chat's model writes a title after the first response. On local runtimes, this can briefly delay your next message."
                : "Use the first message as the chat title"
            }
            label="Chat Titles"
          >
            <DropdownMenu>
              <DropdownMenuTrigger
                render={
                  <button
                    className="flex h-7 items-center gap-1.5 rounded-md border px-2 text-[13px] outline-none hover:bg-muted/50 data-popup-open:bg-muted"
                    type="button"
                  />
                }
              >
                {titles.label}
                <ChevronDownIcon className="size-3.5 text-muted-foreground" />
              </DropdownMenuTrigger>
              <DropdownMenuContent align="end" className="w-48 p-1" sideOffset={6}>
                <DropdownMenuRadioGroup onValueChange={(value) => setGeneral({ chatTitles: value as General["chatTitles"] })} value={titles.id}>
                  {TITLES.map((item) => (
                    <DropdownMenuRadioItem className="h-[26px] rounded-md py-0 text-[13px] font-normal" key={item.id} value={item.id}>
                      {item.label}
                    </DropdownMenuRadioItem>
                  ))}
                </DropdownMenuRadioGroup>
              </DropdownMenuContent>
            </DropdownMenu>
          </Row>
        </Section>
      </div>
    </PageScroll>
  );
}
